// État des traductions : complétude de chaque langue par rapport à l'anglais (langue source), écrit dans
// docs/translations/STATUS.md. `--check` ne réécrit rien et échoue si le fichier n'est pas à jour (CI).
//   pnpm i18n:status           régénère le fichier
//   node scripts/i18n-status.mjs --check
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const locales = join(root, "src/locales");
const out = join(root, "docs/translations/STATUS.md");
const SOURCE = "en";

const flatten = (t, prefix = "") => Object.entries(t).flatMap(([k, v]) => (typeof v === "string" ? [[prefix + k, v]] : flatten(v, `${prefix}${k}.`)));
const load = (lang) => {
  const dir = join(locales, lang);
  const keys = new Map();
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".json")).sort()) {
    for (const [k, v] of flatten(JSON.parse(readFileSync(join(dir, f), "utf8")))) keys.set(`${f.replace(/\.json$/, "")}:${k}`, v);
  }
  return keys;
};

const langs = readdirSync(locales).filter((n) => !n.startsWith(".") && n !== SOURCE).sort();
const source = load(SOURCE);
let md = `# Translation status\n\n_Generated by \`pnpm i18n:status\` — do not edit by hand. English (\`${SOURCE}\`) is the source language: ${source.size} texts._\n\n`;
md += "| Language | Translated | Missing | Complete |\n|---|---:|---:|---:|\n";
const missingByLang = {};
for (const lang of langs) {
  const keys = load(lang);
  const missing = [...source.keys()].filter((k) => !keys.has(k) || keys.get(k).trim() === "");
  missingByLang[lang] = missing;
  const done = source.size - missing.length;
  md += `| \`${lang}\` | ${done} | ${missing.length} | ${((done / source.size) * 100).toFixed(1)} % |\n`;
}
md += "\nA language is shipped in the app once it is at least 90 % complete; missing texts fall back to English.\n";
for (const lang of langs) {
  if (missingByLang[lang].length === 0) continue;
  md += `\n## Missing in \`${lang}\`\n\n${missingByLang[lang].map((k) => `- \`${k}\``).join("\n")}\n`;
}

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* absent */ }
  if (current.replace(/\r\n/g, "\n") !== md) { // fins de ligne : Git peut les convertir sous Windows
    console.error("docs/translations/STATUS.md is out of date: run `pnpm i18n:status` and commit it.");
    process.exit(1);
  }
} else {
  writeFileSync(out, md);
  console.log(`wrote ${out}`);
}
