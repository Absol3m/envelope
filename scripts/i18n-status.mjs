// État des traductions : complétude de chaque langue par rapport à l'anglais (langue source), textes « à revoir »
// (anglais modifié depuis la dernière validation de la traduction), écrit dans docs/translations/STATUS.md.
//   pnpm i18n:status                     régénère le fichier
//   pnpm i18n:status -- --accept fr      marque la traduction `fr` comme à jour par rapport à l'anglais actuel
//   node scripts/i18n-status.mjs --check échoue si le fichier n'est pas à jour (CI)
// Contexte des textes ambigus : docs/translations/context.json (« espace:clé » → description).
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const locales = join(root, "src/locales");
const out = join(root, "docs/translations/STATUS.md");
const reviewedDir = join(root, "docs/translations/reviewed");
const contextFile = join(root, "docs/translations/context.json");
const SOURCE = "en";

const flatten = (t, prefix = "") => Object.entries(t).flatMap(([k, v]) => (typeof v === "string" ? [[prefix + k, v]] : flatten(v, `${prefix}${k}.`)));
const load = (lang) => {
  const dir = join(locales, lang);
  const keys = new Map();
  for (const f of readdirSync(dir).filter((n) => n.endsWith(".json")).sort()) {
    for (const [k, v] of flatten(JSON.parse(readFileSync(join(dir, f), "utf8")))) keys.set(`${f.replace(/\.json$/, "")}:${k}`, v);
  }
  return keys;
};
const hash = (text) => createHash("sha1").update(text).digest("hex").slice(0, 8);
const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : fallback);

const langs = readdirSync(locales).filter((n) => !n.startsWith(".") && n !== SOURCE).sort();
const source = load(SOURCE);
const context = readJson(contextFile, {});

const acceptIndex = process.argv.indexOf("--accept");
if (acceptIndex >= 0) {
  const lang = process.argv[acceptIndex + 1];
  if (!langs.includes(lang)) { console.error(`unknown language: ${lang}`); process.exit(1); }
  const keys = load(lang);
  const reviewed = Object.fromEntries([...source].filter(([k]) => keys.has(k)).map(([k, v]) => [k, hash(v)]));
  mkdirSync(reviewedDir, { recursive: true });
  writeFileSync(join(reviewedDir, `${lang}.json`), JSON.stringify(reviewed, null, 1) + "\n");
}

const describe = (k) => `- \`${k}\` — “${source.get(k).replace(/\n/g, " ↵ ")}”${context[k] ? ` _(${context[k]})_` : ""}`;
let md = `# Translation status\n\n_Generated by \`pnpm i18n:status\` — do not edit by hand. English (\`${SOURCE}\`) is the source language: ${source.size} texts. The part before the colon of a key is the screen it belongs to (\`src/locales/<language>/<screen>.json\`)._\n\n`;
md += "| Language | Translated | Missing | To review | Complete |\n|---|---:|---:|---:|---:|\n";
const detail = {};
for (const lang of langs) {
  const keys = load(lang);
  const reviewed = readJson(join(reviewedDir, `${lang}.json`), {});
  const missing = [...source.keys()].filter((k) => !keys.has(k) || keys.get(k).trim() === "");
  const stale = [...source].filter(([k, v]) => keys.has(k) && reviewed[k] !== undefined && reviewed[k] !== hash(v)).map(([k]) => k);
  detail[lang] = { missing, stale };
  const done = source.size - missing.length;
  md += `| \`${lang}\` | ${done} | ${missing.length} | ${stale.length} | ${((done / source.size) * 100).toFixed(1)} % |\n`;
}
md += "\nA language is shipped in the app once it is at least 90 % complete; missing texts fall back to English. “To review” = the English text changed since the translation was last validated (`pnpm i18n:status -- --accept <lang>` once it is up to date).\n";
for (const lang of langs) {
  const { missing, stale } = detail[lang];
  if (missing.length) md += `\n## Missing in \`${lang}\`\n\n${missing.map(describe).join("\n")}\n`;
  if (stale.length) md += `\n## To review in \`${lang}\`\n\n${stale.map(describe).join("\n")}\n`;
}

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch { /* absent */ }
  if (current.replace(/\r\n/g, "\n") !== md) { // fins de ligne : Git peut les convertir sous Windows
    console.error("docs/translations/STATUS.md is out of date: run `pnpm i18n:status` (and `-- --accept <lang>` once the translation is up to date) and commit it.");
    process.exit(1);
  }
} else {
  writeFileSync(out, md);
  console.log(`wrote ${out}`);
}
